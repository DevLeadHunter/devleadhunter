import type { ProspectionScriptModule, ProspectionScriptSegment } from '~/composables/useProspectionScript'
import type { PreviewVideoResult } from '~/services/storyblokSidecarService'
import type { PresenterVideoTake } from '~/types/PresenterVideoTake'
import type { PresenterVideoTimelinePart } from '~/types/PresenterVideoTimingsCard'
import type { VideoBuildPhase } from '~/types/UiVideoGenerationModal'

export type PresenterVideoConfigProps = {
  module: ProspectionScriptModule
}

/** The words of one module's clip settings; everything else works the same for every module. */
export type PresenterVideoModuleWording = {
  title: string
  subtitle: string
  everyDemoLabel: string
  autoGenerateDetail: string
  flowDetail: string
  recordedCutsDetail: string
  exampleDetail: string
  exampleDemoLabel: string
  exampleDemoPlaceholder: string
  noExampleDemo: string
  resultStepDetail: string
  stayGenericTip: string
  uploadedToast: string
}

/** A demo the takes' example videos are built on: one of the user's demos of the module. */
export type PresenterVideoExampleDemo = {
  id: number
  slug: string
  name: string
}

export type PresenterVideoConfigEmits = {
  'has-video': [hasVideo: boolean]
}

/** How the montage fills the video between the webcam intro and outro: the site's hand-set split, or chapters. */
export type PresenterVideoMiddleLayout =
  | { kind: 'site-split' }
  | {
      kind: 'chapters'
      chapters(middleSeconds: number): PresenterVideoTimelinePart[]
      shortMiddleWarning(middleSeconds: number): string | null
    }

/** What a module brings to the presenter-video settings: its words, its montage, the demos its examples use. */
export type PresenterVideoModuleAdapter = {
  moduleKey: ProspectionScriptModule
  sectionAnchorId: string | null
  wording: PresenterVideoModuleWording
  buildPhases: VideoBuildPhase[]
  scriptStorageKey: string
  fieldIdPrefix: string
  middleLayout: PresenterVideoMiddleLayout
  buildDefaultScript(presenterName: string, companyName: string): ProspectionScriptSegment[]
  renderPreview(demoId: number, take: PresenterVideoTake): Promise<PreviewVideoResult>
  loadExampleDemos(): Promise<PresenterVideoExampleDemo[]>
}
